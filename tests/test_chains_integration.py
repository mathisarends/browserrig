async def test_invalid_input_persists_chain_break_before_skipping_submit(site):
    values, replies, _, result = await _run(
        site,
        _FORM,
        lambda refs: [
            ("set_date", {"ref": refs["Email"], "value": "2026-10-30"}),
            ("click", {"ref": refs["Submit"]}),
        ],
    )
    assert values["clicked"] is None
    assert replies[0].status is ToolStatus.ERROR and replies[0].break_chain
    assert replies[1].status is ToolStatus.SKIPPED
    receipt = next(e for e in result.events if isinstance(e, ToolExecutionFinishedEvent))
    assert receipt.result.break_chain


async def test_tab_actions_keep_their_distinct_kinds_in_durable_receipts(site):
    holder = {}

    class Access(Plugin, needs=(Browser,)):
        async def setup(self, _ctx: Context, browser: Inject[Browser]):
            holder.update(browser=browser, first=browser.active_tab.id)

    step = 0

    async def respond(_request):
        nonlocal step
        step += 1
        if step == 1:
            yield ModelChunk(tool_call=ToolCall("open_tab", {"url": site + "/other"}))
        elif step == 2:
            holder["second"] = holder["browser"].active_tab.id
            yield ModelChunk(tool_call=ToolCall("switch_tab", {"target_id": holder["first"]}))
        elif step == 3:
            yield ModelChunk(tool_call=ToolCall("close_tab", {"target_id": holder["second"]}))
        else:
            yield ModelChunk(text="Done")

    agent = BrowserAgent(
        model=CallbackModel(respond),
        browser=LaunchBrowser(url=site),
        plugins=[Access()],
        approvals=Approvals(default=PolicyDecision.ALLOW),
    )
    result = await agent.run("Manage tabs")
    assert result.text == "Done"
    assert [e.kind for e in result.events if isinstance(e, ActionFinishedEvent)] == [
        ActionKind.OPEN_TAB,
        ActionKind.SWITCH_TAB,
        ActionKind.CLOSE_TAB,
    ]


async def test_reserved_final_summary_uses_effective_limit_and_remains_incomplete(site):
    progress = []

    class Progress(Plugin):
        @hook(PreStep)
        async def before(self, event: PreStep, next_: Next[StepDecision]) -> StepDecision:
            progress.append((event.max_steps, event.remaining_steps, event.is_final_step))
            return await next_()

    model = ScriptedModel(["Partial browser findings"])
    agent = BrowserAgent(
        model=model,
        browser=LaunchBrowser(url=site),
        plugins=[
            AgentLoop(max_steps=10, final_step=FinalStepPolicy.SUMMARIZE),
            Progress(),
        ],
    )
    result = await agent.run("Investigate", max_steps=1)
    assert result.text == "Partial browser findings" and not result.completed
    assert result.stop_reason.value == "max_steps"
    assert progress == [(1, 1, True)]
    assert not model.requests[0].tools


async def _run(site, markup, plan):
    holder, observations = {}, []

    class Page(Plugin, needs=(Browser, Observe)):
        async def setup(self, _ctx: Context, browser: Inject[Browser], observe: Inject[Observe]):
            holder.update(browser=browser, observe=observe)
            await evaluate(browser.active_tab, f"document.body.innerHTML={json.dumps(markup)}")

        @hook(ObservationCapturedEvent)
        async def observed(self, event: ObservationCapturedEvent):
            observations.append(event.observation_id)

    count = 0

    async def respond(request):
        nonlocal count
        count += 1
        if count == 1:
            state = latest(request.messages)
            refs = {element["name"]: element["ref"] for element in state["elements"]}
            holder["delivered"] = holder["observe"].snapshot
            for name, arguments in plan(refs):
                yield ModelChunk(tool_call=ToolCall(name, arguments))
        else:
            yield ModelChunk(text="Done")

    agent = BrowserAgent(
        model=CallbackModel(respond),
        browser=LaunchBrowser(url=site),
        readiness=ReadinessOptions(quiet_ms=30, navigation_min_ms=50),
        approvals=Approvals(default=PolicyDecision.ALLOW),
        plugins=[Page()],
    )
    async with agent.session() as session:
        result = await session.run("Fill the form", max_steps=3)
        values = await evaluate(
            holder["browser"].active_tab,
            "({email:document.querySelector('#email')?.value ?? null, "
            "password:document.querySelector('#password')?.value ?? null, "
            "clicked:document.querySelector('#submit')?.dataset.clicked ?? null})",
        )
        holder["after"] = holder["observe"].snapshot
        replies = [e.result for e in result.events if isinstance(e, ToolCallFinishedEvent)]
        assert result.text == "Done"
        # Probes must not publish extra snapshots or consume the next observation's new markers.
        explicit = sum(
            e.call.name == "observe" and e.result.status is ToolStatus.OK
            for e in result.events
            if isinstance(e, ToolCallFinishedEvent)
        )
        assert len(observations) == 2 + explicit
        return values, replies, holder, result
