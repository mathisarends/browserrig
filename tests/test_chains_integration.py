_FORM = """<style>body{margin:20px} input,select,button{display:block;margin:12px}</style>
    <label>Email<input id=email></label><label>Password<input id=password></label>
    <label>Choice<select><option>One</option><option>Two</option></select></label>
    <button id=submit onclick="this.dataset.clicked='yes'">Submit</button>"""


async def test_form_edits_and_submit_chain_without_cosmetic_interruptions(site):
    markup = _FORM + "<p id=ticker></p><script></script>"
    # Cosmetic changes are generated by input, without introducing an interactive control.
    markup = markup.replace(
        "<input id=email>",
        "<input id=email oninput=\"document.querySelector('#ticker').textContent=this.value\">",
    )
    values, replies, _, _ = await _run(
        site,
        markup,
        lambda refs: [
            ("type_text", {"ref": refs["Email"], "text": "person@example.org"}),
            ("type_text", {"ref": refs["Password"], "text": "secret"}),
            ("select_option", {"ref": refs["Choice"], "value": "Two"}),
            ("click", {"ref": refs["Submit"]}),
        ],
    )
    assert values == {"email": "person@example.org", "password": "secret", "clicked": "yes"}
    assert all(reply.status is ToolStatus.OK and not reply.break_chain for reply in replies)


async def test_typing_reveals_existing_suggestions_and_skips_submit(site):
    markup = _FORM.replace(
        "<input id=email>",
        "<input id=email oninput=\"document.querySelector('#suggestions').hidden=false\">",
    )
    markup += "<div id=suggestions hidden><button>Suggested address</button></div>"
    values, replies, holder, _ = await _run(
        site,
        markup,
        lambda refs: [
            ("type_text", {"ref": refs["Email"], "text": "person"}),
            ("click", {"ref": refs["Submit"]}),
        ],
    )
    assert values["email"] == "person" and values["clicked"] is None
    assert replies[0].break_chain and replies[1].status is ToolStatus.SKIPPED
    assert "Text entered" in replies[0].text
    assert not any(e.name == "Suggested address" for e in holder["delivered"].elements)
    assert any(e.new and e.name == "Suggested address" for e in holder["after"].elements)


async def test_hover_reveals_menu_without_dispatching_click(site):
    markup = (
        _FORM
        + """<style>#menu{display:none} #hover:hover #menu{display:block}</style>
        <div id=hover style='position:absolute;left:300px;top:100px'>
          <button id=hoverbutton
            onclick="document.querySelector('#submit').dataset.clicked='yes'">Menu</button>
          <div id=menu><button>Menu option</button></div></div>"""
    )
    values, replies, _, _ = await _run(
        site,
        markup,
        lambda refs: [
            ("click", {"ref": refs["Menu"]}),
            ("type_text", {"ref": refs["Email"], "text": "should not type"}),
        ],
    )
    assert values["clicked"] is None and values["email"] == ""
    assert replies[0].break_chain and "click was not dispatched" in replies[0].text
    assert replies[1].status is ToolStatus.SKIPPED


